const translations: Record<AppLanguage, Record<TranslationKey, string>> = {
  ja,
  ko,
}

export function isAppLanguage(value: string | null): value is AppLanguage {
  return appLanguages.includes(value as AppLanguage)
}

export function getHtmlLang(language: AppLanguage) {
  return (
    languageOptions.find((option) => option.value === language)?.htmlLang ??
    defaultLanguage
  )
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  params?: Record<string, string | number>,
) {
  const template = translations[language][key] ?? translations.ko[key]

  if (!params) {
    return template
  }

  return Object.entries(params).reduce(
    (message, [paramKey, value]) =>
      message.replace(new RegExp(`{{${paramKey}}}`, 'g'), String(value)),
    template,
  )
}

export function formatAppDate(
  language: AppLanguage,
  date: Date,
  options: Intl.DateTimeFormatOptions,
) {
  return new Intl.DateTimeFormat(language === 'ja' ? 'ja-JP' : 'ko-KR', options)
    .format(date)
    .replace(/\s/g, ' ')
}
